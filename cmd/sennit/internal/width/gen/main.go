// Command gen writes the display-width tables for package width from a Unicode
// EastAsianWidth.txt file.
//
// W (wide) and F (fullwidth) form one table and A (ambiguous) another, each
// merged into contiguous ranges. The source version is recorded in the generated
// file so a reader can tell which Unicode release the tables describe. The
// release should match the unicode package of the Go toolchain that builds the
// command, which for Go 1.26 is 15.0.0:
//
//	curl -sSO https://www.unicode.org/Public/15.0.0/ucd/EastAsianWidth.txt
//	go run ./gen -in EastAsianWidth.txt -out table.go
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
)

type span struct{ lo, hi rune }

func main() {
	in := flag.String("in", "", "path to EastAsianWidth.txt")
	out := flag.String("out", "", "path of the Go file to write")
	flag.Parse()
	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "gen: -in and -out are required")
		os.Exit(2)
	}
	wide, ambiguous, version, err := read(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
	if err := write(*out, wide, ambiguous, version); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func read(path string) (wide, ambiguous []span, version string, err error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, nil, "", err
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		if version == "" && strings.HasPrefix(line, "# EastAsianWidth-") {
			version = strings.TrimSuffix(strings.TrimPrefix(line, "# EastAsianWidth-"), ".txt")
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fields := strings.SplitN(line, ";", 2)
		if len(fields) != 2 {
			return nil, nil, "", fmt.Errorf("malformed line %q", line)
		}
		property := strings.TrimSpace(fields[1])
		if property != "W" && property != "F" && property != "A" {
			continue
		}
		lo, hi, err := parseRange(strings.TrimSpace(fields[0]))
		if err != nil {
			return nil, nil, "", err
		}
		if property == "A" {
			ambiguous = append(ambiguous, span{lo, hi})
		} else {
			wide = append(wide, span{lo, hi})
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, nil, "", err
	}
	if version == "" {
		return nil, nil, "", fmt.Errorf("%s names no EastAsianWidth version", path)
	}
	return merge(wide), merge(ambiguous), version, nil
}

func merge(spans []span) []span {
	sort.Slice(spans, func(i, j int) bool { return spans[i].lo < spans[j].lo })
	merged := spans[:0]
	for _, s := range spans {
		if n := len(merged); n > 0 && s.lo <= merged[n-1].hi+1 {
			if s.hi > merged[n-1].hi {
				merged[n-1].hi = s.hi
			}
			continue
		}
		merged = append(merged, s)
	}
	return merged
}

func parseRange(text string) (rune, rune, error) {
	lo, hi, found := strings.Cut(text, "..")
	if !found {
		hi = lo
	}
	a, err := strconv.ParseUint(lo, 16, 32)
	if err != nil {
		return 0, 0, fmt.Errorf("range %q: %w", text, err)
	}
	b, err := strconv.ParseUint(hi, 16, 32)
	if err != nil {
		return 0, 0, fmt.Errorf("range %q: %w", text, err)
	}
	return rune(a), rune(b), nil
}

func write(path string, wide, ambiguous []span, version string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen from EastAsianWidth-%s.txt. DO NOT EDIT.\n\n", version)
	b.WriteString("package width\n\n")
	b.WriteString("// UnicodeVersion is the release the tables were generated from.\n")
	fmt.Fprintf(&b, "const UnicodeVersion = %q\n\n", version)
	table(&b, "wide lists the East Asian Wide and Fullwidth ranges, sorted and merged.", "wide", wide)
	b.WriteString("\n")
	table(&b, "ambiguous lists the East Asian Ambiguous ranges, sorted and merged.", "ambiguous", ambiguous)
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func table(b *strings.Builder, doc, name string, spans []span) {
	fmt.Fprintf(b, "// %s\n", doc)
	fmt.Fprintf(b, "var %s = [][2]rune{\n", name)
	for _, s := range spans {
		fmt.Fprintf(b, "\t{0x%04X, 0x%04X},\n", s.lo, s.hi)
	}
	b.WriteString("}\n")
}
