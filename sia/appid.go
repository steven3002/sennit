package sia

import "go.sia.tech/core/types"

// appID identifies Sennit to an indexer.
//
// It is a build-time constant and must never change: an app key is issued
// against an app id, so a new id invalidates every key already approved and
// locks users out of the data those keys reach. It is public metadata, not a
// secret.
var appID = types.Hash256{
	0xfe, 0x4c, 0x74, 0x15, 0x57, 0x1b, 0xfc, 0xf5,
	0x64, 0xcd, 0xac, 0x11, 0x43, 0xbd, 0xea, 0x31,
	0x54, 0x3f, 0xf6, 0xa5, 0x99, 0x3e, 0x7d, 0xd5,
	0x87, 0x38, 0xa9, 0x4d, 0xe0, 0xa0, 0x74, 0xc4,
}
